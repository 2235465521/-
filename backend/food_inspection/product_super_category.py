@lru_cache(maxsize=200_000)
def propose_super_category(
    subclass: str,
    major: str = "",
    original: str = "",
) -> tuple[str, str]:
    """
    根据小类（及大类/原名回退）推导超级大类。
    返回 (超级大类, 说明)。
    """
    for name in (subclass, major, original):
        if not name:
            continue
        if name in _SUBCLASS_SUPER:
            return _SUBCLASS_SUPER[name], f"小类映射→{_SUBCLASS_SUPER[name]}"

    for name in (subclass, major, original):
        if not name:
            continue
        for keyword, super_cat in _SUPER_KEYWORD_RULES:
            if keyword in name:
                return super_cat, f"关键词「{keyword}」→{super_cat}"

    return "其他", "未匹配规则"
